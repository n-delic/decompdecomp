const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const path=require('node:path'),root=path.join(__dirname,'..');
const source=fs.readFileSync(path.join(root,'src/decompnet/app/static/js/function.js'),'utf8');
const buttons=['polished','unpolished'].map(kind=>({dataset:{polish:kind},classList:{toggle(name,on){this[name]=on;}},setAttribute(name,value){this[name]=value;}}));
const nodes={};
for(const id of ['fnStatus','fnPolished','fnPolishWhich','fnPolishNote','fnSrcKind'])nodes[id]={};
nodes.fnPolishWhich.querySelectorAll=()=>buttons;
let editor,toast,mapping;
const S={claims:[],ov:{kind:'rom'},polishWhich:'polished',editDirty:false};
const ctx=vm.createContext({S,$:id=>nodes[id],setEditor:text=>editor=text,toast:text=>toast=text,setEditorSourceMapping:value=>mapping=value});
vm.runInContext(source.slice(source.indexOf('function fnBadge('),source.indexOf('function showFnTab(')),ctx);
const detail={name:'f',status:'matched',polished:true,source:'/* readable */ int f(int value) { return value; }',unpolished_source:'int f(int x) { return x; }',source_kind:'matched'};
S.fnDetail=detail;ctx.fnBadge(detail);ctx.renderFunctionSource(detail);
assert.equal(nodes.fnStatus.textContent,'matched');assert.equal(nodes.fnPolished.hidden,false);
assert.equal(editor,detail.source);assert.equal(nodes.fnSrcKind.textContent,'Polished C');
assert.equal(buttons[0]['aria-pressed'],'true');assert.equal(buttons[1].disabled,false);
buttons[1].onclick();assert.equal(editor,detail.unpolished_source);assert.equal(nodes.fnSrcKind.textContent,'Unpolished C');
assert.equal(buttons[1]['aria-pressed'],'true');assert.equal(mapping,null);
ctx.renderFunctionSource(detail);assert.equal(editor,detail.unpolished_source,'polls retain selected version');
S.editDirty=true;buttons[0].onclick();assert.match(toast,/unsaved C/);assert.equal(S.polishWhich,'unpolished');
S.editDirty=false;buttons[0].onclick();assert.equal(editor,detail.source);
S.fnDetail={...detail,unpolished_source:null};ctx.renderFunctionSource(S.fnDetail);
assert.equal(buttons[1].disabled,true);assert.match(nodes.fnPolishNote.textContent,/No version/);
ctx.renderFunctionSource({...S.fnDetail,details_pending:true});assert.match(nodes.fnPolishNote.textContent,/Loading/);
const plain={...detail,status:'open',polished:false,source_kind:'best'};
ctx.fnBadge({...plain,best:null});ctx.renderFunctionSource(plain);
assert.equal(nodes.fnPolished.hidden,true);assert.equal(nodes.fnPolishWhich.hidden,true);
assert.equal(nodes.fnSrcKind.textContent,'Best attempt so far');
assert.match(source,/!S\.fnDetail\?\.polished && !S\.editDirty/, 'late diff response cannot replace comparison');
const css=fs.readFileSync(path.join(root,'src/decompnet/app/static/app.css'),'utf8');
assert.match(css,/\.badge\.polished\s*\{[^}]*background: var\(--polished\)/);
console.log('Polish badges, source switching, refresh, unavailable originals and unsaved edits passed.');
