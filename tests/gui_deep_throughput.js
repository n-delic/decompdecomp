'use strict';
const fs=require('node:fs'), vm=require('node:vm'), assert=require('node:assert/strict');
const elements=new Map();
const get=id=>{if(!elements.has(id))elements.set(id,{dataset:{},textContent:'',hidden:false});return elements.get(id);};
const ctx=vm.createContext({$:get});
vm.runInContext(fs.readFileSync('src/decompnet/app/static/js/deep-progress.js','utf8'),ctx);
const render=ctx.deepProgressView();
render({throughput:{active_compiles:8,compile_slots:10,candidates_per_second:123.45,compiles_per_second:98.76,compiler_queue_seconds:1.2,compiler_setup_seconds:.3,app_cpu_percent:150}});
assert.equal(get('fnDeepThroughput').hidden,false);
assert.match(get('fnDeepThroughput').textContent,/8\/10 compiles active/);
assert.match(get('fnDeepThroughput').textContent,/123.5 candidates\/s/);
assert.match(get('fnDeepThroughput').textContent,/98.8 compiles\/s/);
assert.match(get('fnDeepThroughput').textContent,/compiler and generator processes excluded/);
render({});assert.equal(get('fnDeepThroughput').hidden,true);
render({efficiency:{duplicate_outputs:3,fingerprinted_checks:9}});
assert.match(get('fnDeepNow').textContent,/3 repeated outputs \/ 9 fingerprinted checks/);
assert.match(get('fnDeepNow').textContent,/0 AI tokens/);
render({});assert.doesNotMatch(get('fnDeepNow').textContent,/repeated outputs/);
const html=fs.readFileSync('src/decompnet/app/static/index.html','utf8');
for(const id of ['fnDeepMaximum','deepSweepMaximum','fnDeepCompileSlots','deepSweepCompileSlots'])assert.ok(html.includes(`id="${id}"`));
render({throughput:{local_proposal_generation_seconds:2.5,cleanup_generation_seconds:.1,compiler_execute_seconds:8.2,link_seconds:.4}});
assert.match(get('fnDeepThroughput').textContent,/2.5s local proposals/);
assert.match(get('fnDeepThroughput').textContent,/0.1s cleanup/);
assert.match(get('fnDeepThroughput').textContent,/8.2s compiler work \(summed workers\)/);
assert.match(get('fnDeepThroughput').textContent,/0.4s linking/);

render({throughput:{compiler_slot_utilization_percent:62.5,history_write_seconds:1.2,history_transactions:3}});
assert.match(get('fnDeepThroughput').textContent,/62.5% average slots busy/);
assert.match(get('fnDeepThroughput').textContent,/1.2s history writes \(3 transactions\)/);
