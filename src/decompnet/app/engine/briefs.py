"""What agents read about a function: its assembly, the shared header, a machine draft, who calls it and what
data it uses, look-alikes and twins, its C++ class.

The machine draft (m2c's, seeds.py) is made from the part of the shared header the function uses and remembers what
it was made from (functions.seed_key: those declarations, the names in its assembly, its compiler). When any of that
changes, the draft is made again: on the next brief, and in the background for every open function (app/drafts.py).
"""

from __future__ import annotations

import hashlib
import json
import logging
import re
import struct
import threading

from ... import arch, classes, seeds, similarity
from ...network import NetworkError
from ...project import compiler_for
from ...rom import match
from .common import _ADDRESS, _AUTO_TOKEN

DRAFT_NOTE = "/* machine-generated by m2c: a starting point, not a match */"
# A shared header bigger than this isn't read whole for each function: the brief carries the declarations the
# function uses, and get_context has the rest. A game that shipped with its debug information gets every type and
# global of the game in its first header (consoles/ps2/debuginfo.py): thousands of them. The owner's are 1-8 KB.
BIG_HEADER_BYTES = 16_000
USED_DECLARATIONS_BYTES = 6_000  # of those in one brief, nearest first: what the function names, then what they need
HEADERS_KEPT = 16  # header versions whose declarations are kept read
STALE_BATCH = 500  # functions whose assembly is read at a time, looking for drafts to make again
VTABLE_HEADER_BYTES = 8  # before a C++ vtable's functions: an offset and the type information (classes.py)
MAX_SHOWN_FIELDS = 32  # of a class, in a method's draft (get_class has them all)


class BriefMixin:
    def _layout_key(self, proj) -> tuple:
        """Which functions a game has and their sizes, summed up: a split or a cut changes it, a match doesn't. What a
        brief reads from the whole game (look-alikes, twins) is built again only when it changes."""
        row = self.store.one("SELECT COUNT(*) AS n, COALESCE(MAX(id), 0) AS hi, COALESCE(SUM(size), 0) AS bytes "
                             "FROM functions WHERE project_id=?", proj["id"])
        return tuple(row)

    def warm_briefs(self, proj) -> None:
        """Build what claim briefs read from the whole game: cross-references, C++ classes, look-alikes, twins, the
        compiler map. On GTA San Andreas the first brief took 5.2 s (classes 3 s, look-alikes 1.2 s, twins 0.7 s).
        Once per layout of the game, one build at a time: a brief asked meanwhile waits for it instead of building
        the same things beside it."""
        if not self.is_rom(proj):
            return
        layout = self._layout_key(proj)
        if self._warmed.get(proj["id"]) == layout:
            return
        with self._warming.setdefault(proj["id"], threading.Lock()):
            if self._warmed.get(proj["id"]) == layout:
                return
            for build in (self.xrefs, self.classes, self.structs, self._rom_ops, self.twins.prints, self.compiler_map):
                try:
                    build(proj)
                except Exception:  # a heuristic that fails is missing from briefs, never in their way
                    logging.getLogger("decompdecomp").exception("preparing briefs: %s failed", build.__name__)
            self._warmed[proj["id"]] = layout

    def warm_briefs_soon(self, slug: str) -> None:
        """warm_briefs in the background, then the machine drafts: when a project opens, or helpers start on it."""
        def work() -> None:
            try:
                self.warm_briefs(self._project(slug))
            except NetworkError:
                return  # removed meanwhile
            self.drafter.start(slug)  # every open function's machine draft, kept up to date
        threading.Thread(target=work, daemon=True, name=f"briefs-{slug}").start()

    def _twin_lines(self, proj, fn) -> list[str]:
        """For a brief: the matched function with the same code, and its C with this one's names."""
        try:
            twin_id = self.twins.twin_of(proj, fn["id"])
        except Exception:
            return []
        if twin_id is None:
            return []
        a = self.store.one("SELECT * FROM functions WHERE id=?", twin_id)
        source = self.twins.source_for(proj, a, fn)
        out = ["", f"### Identical code: {a['name']} is the same machine code and already matches"]
        if source and len(source) < 6000:
            out += ["Its C with this function's names (try it first):", "```c", source.strip(), "```"]
        return out

    def _asm_text(self, fn, proj) -> str:
        if not self.is_rom(proj):
            return super()._asm_text(fn, proj)
        return self.rename_tokens(proj, fn["asm"])

    def _header_index(self, project_id: int, ctx, for_m2c: bool = True) -> seeds.HeaderIndex:
        """The declarations of a header version, read once: as m2c reads them (C only), or all of them (the brief's,
        for agents who write C++ too)."""
        key = (project_id, ctx["version"], for_m2c)
        found = self._headers.get(key)
        if found is None:
            found = seeds.HeaderIndex(seeds.c_only(ctx["header"]) if for_m2c else ctx["header"])
            if len(self._headers) >= HEADERS_KEPT:
                self._headers.pop(next(iter(self._headers)))  # the oldest
            self._headers[key] = found
        return found

    def _current_names(self, proj, names) -> set[str]:
        """Names from a function's stored assembly as its brief shows them: automatic ones under their names now."""
        syms = self.symbols(proj["id"])
        return {syms.name_at(int(n[-8:], 16))[0] if _AUTO_TOKEN.fullmatch(n) else n for n in names}

    def _draft_plan(self, fn, proj, names=None, ctx=None) -> tuple[str, str, str]:
        """(key, toolchain, context) of a function's machine draft: its compiler (its address range's), the
        declarations of the shared header it uses, and what the key says it's made from. m2c reads a function's own
        declaration and its callees' and globals' from the header, and the types those need, nothing else: on the
        owner's games 116 of 120 drafts made from those declarations alone were the same as with the whole header,
        and the other 4 were better (a declaration elsewhere in the header made m2c's reading of it fail)."""
        own = compiler_for(self.cfg(proj), fn["vram"])
        target = seeds.m2c_target(own["toolchain"]) or ""
        ctx = ctx or self._context(proj["id"], fn["unit"])
        roots = self._current_names(proj, seeds.asm_names(fn["asm"] or "") if names is None else names)
        used = self._header_index(proj["id"], ctx).used(roots)
        context = "\n".join(d.text for d in used if not d.text.startswith("#"))
        key = hashlib.sha1(json.dumps([target, own["toolchain"], own.get("flags", []), sorted(roots), context])
                           .encode()).hexdigest()[:16]
        return key, own["toolchain"], context

    def _seed_for(self, fn, proj) -> str | None:
        """m2c draft, made the first time someone opens the function or the background drafter gets to it, and again
        when what it's made from changed (_draft_plan). Drafts of different functions are made side by side: one lock
        for the whole app made agents claiming at once wait for each other's drafts, about 0.3 s each."""
        if not seeds.available():
            return fn["seed"]
        key, toolchain, context = self._draft_plan(fn, proj)
        if fn["seed"] is not None and fn["seed_key"] == key:
            return fn["seed"]
        with self._draft_locks.setdefault(fn["id"], threading.Lock()):
            row = self.store.one("SELECT seed, seed_key FROM functions WHERE id=?", fn["id"])
            if row is None or (row["seed"] is not None and row["seed_key"] == key):  # made meanwhile
                return row["seed"] if row else None
            data_asm = "\n".join(self._jtbl_asm(proj, fn)) if "jtbl_" in (fn["asm"] or "") else None
            draft = seeds.generate_from_asm(self._asm_text(fn, proj), fn["name"], toolchain, context, data_asm)
            text = f"{DRAFT_NOTE}\n{draft}" if draft else ""
            with self.store.tx() as db:
                db.execute("UPDATE functions SET seed=?, seed_key=? WHERE id=?", (text, key, fn["id"]))
        return text

    def stale_drafts(self, proj) -> list[int]:
        """Open functions whose machine draft is missing or was made from something that changed since, smallest
        first (claims go smallest first too). The names in each function's assembly are read once per size of it
        (a split changes it): on GTA San Andreas, reading all 69 MB of its open functions' assembly takes 1.2 s."""
        names = self._asm_names.setdefault(proj["id"], {})
        rows = self.store.all("SELECT id, size, unit, vram, seed, seed_key FROM functions WHERE project_id=? "
                              "AND status='open' ORDER BY n_insns, vram", proj["id"])
        unread = [r["id"] for r in rows if names.get(r["id"], (None,))[0] != r["size"]]
        for at in range(0, len(unread), STALE_BATCH):
            ids = unread[at:at + STALE_BATCH]
            for r in self.store.all(f"SELECT id, size, asm FROM functions WHERE id IN ({','.join('?' * len(ids))})", *ids):
                names[r["id"]] = (r["size"], frozenset(seeds.asm_names(r["asm"] or "")))
        contexts: dict[str, object] = {}
        for unit in {r["unit"] for r in rows}:
            contexts[unit] = self._context(proj["id"], unit)
        return [r["id"] for r in rows if r["seed"] is None
                or r["seed_key"] != self._draft_plan(r, proj, names[r["id"]][1], contexts[r["unit"]])[0]]

    def draft_mark(self, proj) -> tuple:
        """What drafts are made from, summed up: a new header version, compiler, rename or split changes it."""
        version = self.store.one("SELECT MAX(version) AS v FROM context_versions WHERE project_id=?", proj["id"])["v"]
        event = self.store.one("SELECT MAX(id) AS e FROM events WHERE project_id=? AND kind IN "
                               "('context', 'compiler', 'rename', 'split', 'sync', 'import')", proj["id"])["e"]
        return version, event, self._layout_key(proj)

    def can_draft(self, proj) -> bool:
        """Whether this project's functions get machine drafts here: a ROM project, with m2c installed and able to
        read its code."""
        return (self.is_rom(proj) and seeds.available()
                and bool(seeds.m2c_target(self.cfg(proj)["compiler"]["toolchain"])))

    def redraft(self, project: str | None, function: str, context: str) -> str:
        """m2c's draft of a function made again with declarations an agent worked out (a struct, a prototype) on top
        of the shared header's, replacing the header's where they declare the same names. Recorded nowhere: the agent
        tries it with compile_and_diff, and shares what helped with edit_context."""
        self._rom_only(project, "redraft")
        proj = self._project(project)
        fn = self._function(function, proj["slug"])
        if not seeds.available():
            raise NetworkError("redraft needs m2c, the draft decompiler: the user can install it in Setup")
        own = compiler_for(self.cfg(proj), fn["vram"])
        if not seeds.m2c_target(own["toolchain"]):
            raise NetworkError("m2c can't read this function's code (no draft decompiler for its compiler)")
        mine = seeds.declarations(seeds.c_only(context))
        if not mine:
            raise NetworkError("pass the declarations to draft with in `context` (a struct, a prototype, an extern)")
        declared = set().union(*(d.names for d in mine))
        roots = self._current_names(proj, seeds.asm_names(fn["asm"] or "")) | set().union(*(d.uses for d in mine))
        index = self._header_index(proj["id"], self._context(proj["id"], fn["unit"]))
        theirs = [d.text for d in index.used(roots) if not d.text.startswith("#") and not (d.names and d.names <= declared)]
        data_asm = "\n".join(self._jtbl_asm(proj, fn)) if "jtbl_" in (fn["asm"] or "") else None
        try:
            draft = seeds.generate_from_asm(self._asm_text(fn, proj), fn["name"], own["toolchain"],
                                            "\n".join(theirs + [d.text for d in mine]), data_asm, strict=True)
        except seeds.DraftError as e:
            raise NetworkError(f"m2c couldn't make the draft with your declarations: {e}") from None
        if not draft:
            raise NetworkError(f"m2c made no draft of {fn['name']}")
        replaced = sorted(declared & set(index.by_name))
        return (f"m2c's draft of {fn['name']} with your declarations"
                + (f" (yours replace the header's {', '.join(replaced[:8])})" if replaced else "")
                + ". Recorded nowhere: try it with compile_and_diff, and add the declarations that helped to the "
                  "header with edit_context, so every draft and agent gets them.\n```c\n" + draft.strip() + "\n```")

    def _jtbl_asm(self, proj, fn) -> list[str]:
        out = [".section .rodata"]
        read = self.reader(proj)
        syms = self.symbols(proj["id"])
        for m in sorted(set(re.findall(r"jtbl_([0-9A-F]{8})", fn["asm"]))):
            addr = int(m, 16)
            sym = syms.by_addr.get(addr)
            size = sym.size if sym and sym.size else 0
            data = read(addr, size) if size else None
            if not data:
                continue
            out.append(f"dlabel {syms.label(addr)}")
            fmt = ">I" if self.cfg(proj).get("big_endian", True) else "<I"
            for (w,) in struct.iter_unpack(fmt, data[:len(data) // 4 * 4]):
                out.append(f".word .L{w:08X}" if fn["vram"] <= w < fn["vram"] + fn["size"] else f".word 0x{w:08X}")
        return out

    def get_context(self, project: str | None, function: str | None = None) -> str:
        self._rom_only(project, "get_context")
        return super().get_context(project, function)

    def _brief(self, fn, agent, header):
        if self.cfg(self.store.one("SELECT config FROM projects WHERE id=?", fn["project_id"])).get("kind") == "fork":
            return self.forks.brief(fn, agent, header)
        proj = self.store.one("SELECT * FROM projects WHERE id=?", fn["project_id"])
        if self.is_rom(proj) and fn["status"] == "open" and not fn["best_source"]:
            self._seed_for(fn, proj)  # made again first when what it's made from changed
            fn = self._function(fn["name"], proj["slug"])
            if fn["seed"]:
                fn = dict(fn) | {"seed": self._draft_shown(fn, proj)}
        return super()._brief(fn, agent, header)

    def xrefs(self, proj) -> dict:
        """calls / called_by / uses / used_by, all keyed by address."""
        if proj["id"] in self._xrefs:
            return self._xrefs[proj["id"]]
        funcs = self.store.all("SELECT name, vram, size, relocs FROM functions WHERE project_id=?", proj["id"])
        starts = {f["vram"] for f in funcs}
        calls, called_by, uses, used_by = {}, {}, {}, {}
        for f in funcs:
            for off, rtype, addr in json.loads(f["relocs"]):
                if f["vram"] <= addr < f["vram"] + f["size"]:
                    continue
                if addr in starts:
                    calls.setdefault(f["vram"], set()).add(addr)
                    called_by.setdefault(addr, set()).add(f["vram"])
                elif rtype not in (match.R_MIPS_26, 10):  # 10: a Thumb call (GBA) to something not known as a function
                    uses.setdefault(f["vram"], set()).add(addr)
                    used_by.setdefault(addr, set()).add(f["vram"])
        self._xrefs[proj["id"]] = {"calls": calls, "called_by": called_by, "uses": uses, "used_by": used_by}
        return self._xrefs[proj["id"]]

    def classes(self, proj) -> classes.Classes | None:
        """The C++ classes found in a MIPS game's code (classes.py), kept with the cross-references (renames keep
        addresses; splits and cuts drop both). None: not MIPS code."""
        if not self.is_rom(proj) or arch.CLASSES not in self.console(proj).features:
            return None
        x = self.xrefs(proj)
        if "classes" not in x:
            rows = self.store.all("SELECT vram, target, relocs FROM functions WHERE project_id=? AND target IS NOT NULL",
                                  proj["id"])
            x["classes"] = classes.recover(((r["vram"], r["target"], json.loads(r["relocs"])) for r in rows),
                                           self.reader(proj), bool(self.cfg(proj).get("big_endian", True)))
        return x["classes"]

    def get_class(self, project: str | None, what: str = "") -> str:
        self._rom_only(project, "get_class")
        proj = self._project(project)
        found = self.classes(proj)
        if found is None:
            raise NetworkError("get_class reads MIPS code (PlayStation 2, PlayStation, N64) for now")
        syms = self.symbols(proj["id"])
        if not found.by_vtable:
            return "No C++ classes found: no function stores a vtable (a table of function addresses) into an object."
        what = what.strip()
        if not what:
            rows = sorted(found.by_vtable.values(), key=lambda c: (-len(c.slots), c.vtable))
            return (f"{len(rows)} classes, found from the vtables their constructors store (largest first; "
                    f"get_class(vtable or function) has one's fields and virtual functions):\n"
                    + "\n".join(f"- {syms.label(c.vtable)} (0x{c.vtable:08X}): {len(c.slots)} virtual functions, "
                                 f"{len(c.fields)} fields seen, at least 0x{c.size_seen():X} bytes"
                                 + (f", base {syms.label(c.parent)}" if c.parent is not None else "") for c in rows[:60]))
        m = _ADDRESS.match(what)
        addr = int(m.group(1), 16) if m else syms.resolve(what)
        if addr is None:
            fn = self.store.one("SELECT vram FROM functions WHERE project_id=? AND name=?", proj["id"], what)
            addr = fn["vram"] if fn else None
        hits = found.find(addr) if addr is not None else []
        if not hits:
            raise NetworkError(f"`{what}` isn't a vtable, or a virtual function, constructor or destructor of one of the "
                               f"{len(found.by_vtable)} classes found in this game's code: get_class() lists them")
        return "\n\n".join(classes.describe(c, found, syms.label, focus=addr) for c in hits[:3])

    def _class_brief(self, fn, proj) -> list[str]:
        """What get_function says about a virtual function, constructor or destructor: its class and the fields of
        `this` it uses, so agents write this->field at the right offsets."""
        try:
            found = self.classes(proj)
        except Exception:  # a heuristic: it never stands between an agent and the function
            logging.getLogger("decompdecomp").exception("finding C++ classes failed")
            return []
        roles = found.roles.get(fn["vram"]) if found else None
        if not roles:
            return []
        syms = self.symbols(proj["id"])
        lines = ["", "### C++ class (found from the vtables constructors store; get_class has the whole layout)"]
        for vt, role in roles[:3]:
            cls = found.by_vtable[vt]
            used = [f"+0x{o:X} {f.ctype()}" for o, f in sorted(cls.fields.items()) if fn["vram"] in f.users]
            base = f", base class {syms.label(cls.parent)}" if cls.parent is not None else ""
            lines.append(f"- {role} of {syms.label(vt)} ({len(cls.slots)} virtual functions{base}); vtable pointer at "
                         f"+0x{cls.vptr:X}" + (f"; this function uses {', '.join(used[:16])}" if used else ""))
        return lines

    def _own_class(self, proj, vram: int) -> tuple[classes.Class | None, str]:
        """The class a function is a method of, and what it is there ("virtual function 3"), when the class recovery
        is sure: one class, or one class whose subclasses inherit it (a virtual function a subclass doesn't override
        is in its vtable too, at the same slot). And only a class whose vtable starts like a C++ compiler's (a zero
        in its two header words: the offset, or no type information): a C game's table of functions starts with
        functions."""
        found = self.classes(proj)
        roles = found.roles.get(vram, []) if found else []
        owners = {vt for vt, _ in roles}
        owners = {vt for vt in owners if found.by_vtable[vt].parent not in owners}
        if len(owners) != 1:
            return None, ""
        cls = found.by_vtable[owners.pop()]
        head = self.reader(proj)(cls.vtable, VTABLE_HEADER_BYTES)
        e = ">" if self.cfg(proj).get("big_endian", True) else "<"
        if head is None or 0 not in struct.unpack(e + "2I", head):
            return None, ""
        role = next(r for vt, r in roles if vt == cls.vtable)
        return cls, (f"virtual function {role.split()[-1]}" if role.startswith("slot") else "a constructor or destructor")

    def _draft_shown(self, fn, proj) -> str:
        """The machine draft as the brief shows it: m2c writes C, `func(void *arg0, ...)`; where the class recovery
        knows the function is a method, it's shown as `Class::func(...)` with `this` and the class's known fields
        (seeds.method_draft). Only where that's sure: otherwise as m2c wrote it. On GTA San Andreas the class
        recovery knows 3,086 of its 12,627 functions as methods, 2,741 of one class only."""
        try:
            cls, role = self._own_class(proj, fn["vram"])
            if cls is None:
                return fn["seed"]
            # the fields this function uses: a class's can be hundreds (GTA San Andreas: up to 0x400 bytes seen)
            fields = [(offset, f.size, f.ctype()) for offset, f in sorted(cls.fields.items()) if fn["vram"] in f.users]
            label = self.symbols(proj["id"]).label(cls.vtable)
            return seeds.method_draft(fn["seed"], fn["name"], label, fields[:MAX_SHOWN_FIELDS], cls.vptr, role,
                                      more=len(fields) > MAX_SHOWN_FIELDS) or fn["seed"]
        except Exception:  # a way of showing the draft: it never stands between an agent and it
            logging.getLogger("decompdecomp").exception("showing a draft as a C++ method failed")
            return fn["seed"]

    def _types_brief(self, fn, proj) -> list[str]:
        """On a game whose shared header is big (BIG_HEADER_BYTES), the declarations the function's code and its
        draft (or best attempt) use, nearest first, instead of the whole header. What the judge compiles with
        doesn't change: every compile includes the whole header."""
        ctx = self._context(proj["id"], fn["unit"])
        if len(ctx["header"]) <= BIG_HEADER_BYTES:
            return []
        index = self._header_index(proj["id"], ctx, for_m2c=False)
        source = fn["matched_source"] or fn["best_source"] or fn["seed"] or ""
        roots = self._current_names(proj, seeds.asm_names(fn["asm"] or "")) | set(re.findall(r"\b[A-Za-z_]\w*", source))
        near = index.reach(roots)
        kept, size = [], 0
        for i in near:
            if kept and size + len(index.decls[i].text) > USED_DECLARATIONS_BYTES:
                break
            kept.append(i)
            size += len(index.decls[i].text) + 1
        whole = (f"context.h v{ctx['version']} is {len(ctx['header']) // 1000} KB, {len(index.decls)} declarations: "
                 "get_context has all of it, and every compile includes all of it")
        if not kept:
            return ["", f"### Declarations it uses: none of the shared header's ({whole})"]
        lines = ["", f"### Declarations it uses, from the shared header ({len(kept)} of them; {whole})", "```c"]
        lines += [index.decls[i].text for i in sorted(kept)]
        if len(near) > len(kept):
            lines.append(f"/* ... and {len(near) - len(kept)} more declarations these use: get_context */")
        return lines + ["```"]

    def _next_step(self, proj, ctx) -> str:
        if self.is_rom(proj) and len(ctx["header"]) > BIG_HEADER_BYTES:
            return ("Next: write C for this function (the declarations it uses are above; get_context has the whole "
                    "header) and iterate with compile_and_diff until score is 0. Submit only the function body (plus "
                    "any helper declarations); context.h is included automatically.")
        return super()._next_step(proj, ctx)

    def _debug_brief(self, fn, proj) -> list[str]:
        """What the game's own debug information says about the function (Console.debug_info), when it shipped with it."""
        debug = json.loads(fn["meta"] or "{}").get("debug") if "meta" in fn.keys() else None
        return self.console(proj).debug_brief(debug) if debug else []

    def _extra_brief(self, fn, proj) -> list[str]:
        if not self.is_rom(proj):
            return []
        self.warm_briefs(proj)
        syms = self.symbols(proj["id"])
        x = self.xrefs(proj)
        segment = fn["unit"] in {s.get("name") for s in self.cfg(proj).get("segments", [])}  # else its source file
        lines = ["", "### Where it lives",
                 f"address 0x{fn['vram']:08X}, ROM offset 0x{fn['rom_offset']:X}, "
                 f"{'segment' if segment else 'source file'} {fn['unit']}"]
        calls = sorted(x["calls"].get(fn["vram"], ()))
        callers = sorted(x["called_by"].get(fn["vram"], ()))
        if calls:
            lines.append("calls: " + ", ".join(syms.label(a) for a in calls[:30]))
        if callers:
            lines.append("called by: " + ", ".join(syms.label(a) for a in callers[:30]))
        used = sorted(x["uses"].get(fn["vram"], ()))
        if used:
            lines += ["", "### Data it uses (declare what you need as extern in your source, or in context.h)"]
            prev = {r["name"]: r for r in self.store.all("SELECT name, kind, size, preview FROM symbols WHERE project_id=?", proj["id"])}
            for a in used[:40]:
                name, off = syms.name_at(a)
                r = prev.get(name)
                desc = f"{r['kind']}, {r['size']} bytes" if r else "unknown size"
                if r and r["preview"]:
                    desc += f": {r['preview']}"
                lines.append(f"- {syms.label(a)} (0x{a:08X}; {desc})")
        # the brief's sections after those: one method each, (fn, proj) -> its lines (none when it has nothing to say);
        # _struct_brief (layouts.py): its pointer arguments' likely structs
        for section in (self._debug_brief, self._class_brief, self._types_brief, self._compiler_brief, self._struct_brief):
            lines += section(fn, proj)
        twin = self._twin_lines(proj, fn) if fn["status"] != "matched" else []
        lines += twin
        alike = [] if twin else [(r, sim) for r, sim in self.similar(proj, fn, top=3) if r["status"] == "matched"]
        if alike:
            lines += ["", "### Looks like (already matched; read with get_function)",
                      ", ".join(f"{r['name']} ({sim * 100:.0f}% similar)" for r, sim in alike)]
            r, sim = alike[0]
            src = self.store.one("SELECT matched_source FROM functions WHERE project_id=? AND name=?", proj["id"], r["name"])
            if sim >= 0.8 and src and src["matched_source"] and len(src["matched_source"]) <= 3000:
                # nearly the same code: its matching C is the best starting point there is (saves a tool call)
                lines += [f"Matching C of {r['name']} ({sim * 100:.0f}% similar): start from this",
                          "```c", src["matched_source"].strip(), "```"]
        lines += ["", "Names: use the names shown here (or rename_symbol to give an address a real name). "
                      "Your code is linked at this function's address and must reproduce the ROM bytes exactly."]
        return lines

    def _rom_ops(self, proj) -> dict[tuple[int, int], list[str]]:
        """(vram, size) -> mnemonics of every function, cached until the game's layout changes (renames keep
        addresses; splits change sizes). Every brief read every function's code again to find out (50 ms on GTA San
        Andreas); now that's only after a split or a cut, and only new functions are decoded."""
        layout = self._layout_key(proj)
        known = self._ops.get(proj["id"])
        if known and known[0] == layout:
            return known[1]
        cache = dict(known[1]) if known else {}  # a new dict: a reader of the old one never sees it change
        rows = self.store.all("SELECT vram, size, target FROM functions WHERE project_id=? AND target IS NOT NULL", proj["id"])
        live = set()
        for r in rows:
            key = (r["vram"], r["size"])
            live.add(key)
            if key not in cache:
                cache[key] = similarity.mips_mnemonics(r["target"], bool(proj["big_endian"]), r["vram"] or 0)
        for key in set(cache) - live:
            del cache[key]
        self._ops[proj["id"]] = (layout, cache)
        return cache

    def similar(self, proj, fn, top: int = 5) -> list[tuple[dict, float]]:
        """Functions whose instructions look like `fn`'s, matched ones first: [(row, similarity)]."""
        if fn["target"] is None:
            return []
        ops = self._rom_ops(proj)
        me = (fn["vram"], fn["size"])
        if me not in ops:
            return []
        cands = {f"{v}:{n}": o for (v, n), o in ops.items() if (v, n) != me}
        ranked = similarity.rank(ops[me], cands, top=top * 2)
        # only the rows of those: reading every function's (12,627 on GTA San Andreas) took a third of a brief, and
        # with 8 agents at once, briefs waited on each other row by row (8 agents briefing 24 functions: 5.9 s; with
        # only these rows, 1.4-1.9 s)
        vrams = [int(key.split(":")[0]) for key, _ in ranked]
        rows = {(r["vram"], r["size"]): r for r in self.store.all(
            f"SELECT name, vram, size, n_insns, status, best_score FROM functions WHERE project_id=? AND vram IN "
            f"({','.join('?' * len(vrams))})", proj["id"], *vrams)} if vrams else {}
        out = []
        for key, sim in ranked:
            v, n = (int(x) for x in key.split(":"))
            if (v, n) in rows:
                out.append((rows[(v, n)], sim))
        out.sort(key=lambda x: (x[0]["status"] != "matched", -x[1]))
        return out[:top]

    def find_similar(self, project: str | None, function: str, limit: int = 5) -> str:
        if (fork := self.fork_slug(project)):
            return self.forks.find_similar(fork, function, limit)
        proj = self._project(project)
        fn = self._function(function, proj["slug"])
        hits = self.similar(proj, fn, top=max(1, min(int(limit), 15)))
        if not hits:
            return f"No look-alikes found for {fn['name']}."
        lines = [f"Functions that look like {fn['name']}:"]
        for r, sim in hits:
            state = "matched" if r["status"] == "matched" else f"best {r['best_score']}" if r["best_score"] is not None else "not started"
            lines.append(f"- {r['name']}  {sim * 100:.0f}% similar  {state}  ({r['n_insns']} insns, 0x{r['vram']:08X})")
        best = next((r for r, _ in hits if r["status"] == "matched"), None)
        if best is not None:
            src = self.store.one("SELECT matched_source FROM functions WHERE project_id=? AND name=?", proj["id"], best["name"])
            if src and src["matched_source"]:
                lines += ["", f"Matching C of {best['name']}:", "```c", src["matched_source"].strip()[:4000], "```"]
        return "\n".join(lines)

    def list_functions(self, project: str | None, status: str = "open", limit: int = 40) -> str:
        if (fork := self.fork_slug(project)):
            return self.forks.list_functions(fork, status, limit)
        proj = self._project(project)
        where = "" if status == "all" else " AND f.status=?"
        args = [proj["id"]] + ([] if status == "all" else [status])
        rows = self.store.all(
            f"SELECT f.name, f.vram, f.n_insns, f.status, f.best_score, a.name AS claimed_by FROM functions f "
            f"LEFT JOIN claims c ON c.function_id=f.id LEFT JOIN agents a ON a.id=c.agent_id "
            f"WHERE f.project_id=?{where} ORDER BY f.vram LIMIT ?", *args, limit)
        if not rows:
            return f"No {status} functions."
        return "\n".join(f"- {r['name']} @0x{r['vram']:08X}: {r['n_insns']} insns, {r['status']}"
                         + (f", best score {r['best_score']}" if r["best_score"] is not None else "")
                         + (f", claimed by {r['claimed_by']}" if r["claimed_by"] else "") for r in rows)

    def read_data(self, project: str | None, what: str, length: int = 64) -> str:
        self._rom_only(project, "read_data")
        proj = self._project(project)
        syms = self.symbols(proj["id"])
        m = _ADDRESS.match(what.strip())
        addr = int(m.group(1), 16) if m else syms.resolve(what.strip())
        if addr is None:
            raise NetworkError(f"`{what}` is not an address or a known symbol")
        length = max(4, min(int(length), 512))
        data = self.reader(proj)(addr, length)
        head = f"{syms.label(addr)} at 0x{addr:08X}"
        if data is None:
            sym = syms.by_addr.get(addr)
            if sym and sym.kind == "bss":
                return f"{head}: uninitialized data (.bss), {sym.size} bytes; it starts as zeros at boot."
            return f"{head}: not in a loaded part of the ROM (maybe .bss, or a segment that isn't split yet)."
        out = [head]
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            text = "".join(chr(c) if 32 <= c < 127 else "." for c in chunk)
            out.append(f"  {addr + i:08X}: {chunk.hex(' '):<47}  {text}")
        e = ">" if self.cfg(proj).get("big_endian", True) else "<"
        words = [w for (w,) in struct.iter_unpack(e + "I", data[:len(data) // 4 * 4])]
        low, high = self.console(proj).ram  # #4.12: N64 addresses only, before, never a PS2 game's
        ptrs = [f"+0x{4 * i:X}: {syms.label(w)}" for i, w in enumerate(words) if low <= w < high]
        if ptrs:
            out.append("words that look like addresses: " + ", ".join(ptrs[:16]))
        floats = [struct.unpack(e + "f", struct.pack(e + "I", w))[0] for w in words[:8]]
        if any(1e-6 < abs(f) < 1e7 for f in floats):
            out.append("as f32: " + ", ".join(f"{f:g}" for f in floats))
        return "\n".join(out)
