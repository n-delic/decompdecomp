"""Conservative local triage of captured repairs, not proof of why a function matched.

Group duplicate evidence and describe token changes. Reviewed examples remain available; only a
provenance-backed installed automatic path is labelled implemented. No rule is enabled here.
"""
import difflib
import hashlib
import json
import re

from . import repair_changes

TYPE_WORDS = {'char','short','int','long','float','double','signed','unsigned','void',
              's8','u8','s16','u16','s32','u32','s64','u64','f32','f64','struct','typedef'}


def identity(example):
    e = example['evidence']
    after = e.get('after') or {}
    # Full captured settings prevent compiler/header/build changes being mistaken for a duplicate.
    key = (example.get('project_id'), e.get('target_sha256'), after.get('source_sha256'),
           after.get('context_version'), after.get('settings'))
    if not key[1] or not key[2] or not key[4]:
        return None
    return hashlib.sha256(json.dumps(key, sort_keys=True).encode()).hexdigest()


def classify(example):
    e = example['evidence']
    before, after = e.get('before') or {}, e.get('after') or {}
    old, new = before.get('source'), after.get('source')
    provenance = e.get('provenance') or {}
    kind = repair_changes.kind(old, new or '')
    patterns = []
    category, note = 'other', 'Grouped source evidence; multiple or insufficiently isolated changes need a controlled replay.'
    status = 'reviewed'
    automatic = provenance.get('kind') in {'deterministic draft repair', 'machine draft', 'deep local repair', 'random rewrite', 'automatic candidate'}
    if automatic and provenance.get('family'):
        status = 'implemented'
        note = 'Already generated by the recorded automatic path: ' + str(provenance['family']) + '. Retained for regression review.'
    if kind == 'missing_before':
        note += ' No saved failed C; no isolated repair can be inferred.'
    elif kind in {'unchanged', 'comments_or_spacing'}:
        category = 'compiler_settings' if before.get('settings') != after.get('settings') else 'other'
        note += ' C tokens/line boundaries did not change; inspect build context and verification history.'
    elif kind == 'layout_only':
        category = 'layout'
        note += ' C tokens unchanged; source layout sensitivity is a hypothesis, not a proved mechanism.'
    else:
        trim = lambda text: re.sub(r'#ifndef M2C_DEFINES.*?#endif', '', text or '', flags=re.S)
        a = repair_changes.TOKEN.findall(repair_changes.without_comments(trim(old)))
        b = repair_changes.TOKEN.findall(repair_changes.without_comments(trim(new)))
        changed = []
        for tag, i, j, k, l in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
            if tag != 'equal':
                changed.extend(a[i:j] + b[k:l])
                normalize = lambda tokens: [token if token in TYPE_WORDS or not re.fullmatch(r'[A-Za-z_]\w*|\d+', token)
                                            else 'number' if token.isdigit() else 'identifier' for token in tokens[:40]]
                patterns.append((tag, normalize(a[i:j]), normalize(b[k:l])))
        words = set(changed)
        if words & {'goto','if','else','while','for','switch','case','break','continue'}:
            category = 'control_flow'
        elif words & TYPE_WORDS:
            category = 'types'
        elif words & {'->','['} or any(re.fullmatch(r'D_[0-9A-Fa-f]+', w) for w in words):
            category = 'addresses'
        elif words and all(re.fullmatch(r'\d+|[xXa-fA-F0-9]+|[+*/%<>&|^~()-]', w) for w in words):
            category = 'constants'
        elif words & {'{','}'}:
            category = 'layout'
        elif words & {'=','+=','-=','++','--'}:
            category = 'temporaries'
        else:
            category = 'expression_order'
        note += ' Category describes the source diff; headers and other edits may also contribute.'
    if not e.get('comparable_settings'):
        note += ' Comparable compiler settings were not established.'
    signature = hashlib.sha256(json.dumps((category, kind, provenance.get('family',''), patterns), sort_keys=True).encode()).hexdigest()[:12]
    return dict(category=category, status=status, note=note, group=signature, change=kind)
