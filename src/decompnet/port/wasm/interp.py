"""The functions with no C yet, run by the host's interpreter from the player's ROM (consoles/n64/port_wasm/mips.c):
the build's interp.c, the C between the interpreter and the rest (docs/PORTING.md, "Functions with no C yet").

- Each import of the game's C that names a function with no C (a console address, by its automatic name or the
  split's) is defined here: its arguments where MIPS o32 passes them, then the interpreter runs the function's own
  instructions and its result goes back as o32 returns it. These take the place of stubs.py's, which only said the
  function was missing; the imports the host answers itself (libultra) and those recompiled C defines (recomp.py's
  bridges.c, in a build that has it) are left to them.
- `port_mips_calls`, every function that has C by its console address: the game's own (through its exported
  function, `w2c_game_*`, which the browser's host reaches through the page's table: web.py's glue finds these calls)
  and the host's (libultra's functions it replaces, by name or by library detection's name). Interpreted code
  jumping to one of them runs that C.

The same file serves the native, the browser and the Miyoo Mini's builds: the interpreter needs none of the game's
code at build time, so a build made from the save alone (a GitHub runner's) runs what a local one does, where the
C recompiled from the ROM (recomp.py) can't go.
"""

from __future__ import annotations

import re
from pathlib import Path

from .adapt import REGS, split_top
from .recomp import EXPORT, HOST, IMPORT, _addresses, _demangle, _import_addresses, _vram, o32

# the libultra routines mips.c's shape_identify can name in code loaded at run time (consoles/n64/sdk_shapes.py's
# identify() has the same tests): each the host defines is called in place of the game's copy
SHAPE_NAMES = ("osCreateThread", "osYieldThread", "osStartThread", "osSetThreadPri", "osDestroyThread", "osRecvMesg",
               "osSendMesg", "osJamMesg", "osCreateMesgQueue", "osSetEventMesg")

HEADER = """/* Generated by port/wasm/interp.py: the C between the interpreter (mips.c) and the game's and the host's C. */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "game.h"
w2c_game *port_game(void);
uint32_t port_mips_lw(uint32_t a);
void port_mips_sw(uint32_t a, uint32_t v);
int port_mips_enter(uint64_t *r, uint32_t *f, int words);
uint32_t port_mips_varargs(const uint64_t *r, int first);
uint32_t port_mips_slot(const uint64_t *r, int n);
void port_mips_copy_in(uint64_t *r, int slot, uint32_t from, int words);
uint64_t port_mips_typed_call(uint32_t entry, const uint8_t *types, const uint64_t *vals, unsigned n, int ret);
void port_mips_spread(uint64_t *r, int first, uint32_t buf);
void port_mips_run(uint32_t entry, uint64_t *r, uint32_t *f);
void port_mips_leave(const uint64_t *r);
typedef void (*PortMipsCall)(uint64_t *r, uint32_t *f);
typedef struct { uint32_t vram; PortMipsCall call; } PortMipsEntry;
typedef struct { const uint32_t *words, *masks; uint32_t count; PortMipsCall call; } PortMipsPattern;
typedef struct { const char *name; PortMipsCall call; } PortMipsShape;
const uint32_t port_mips_regs = 0x%(regs)08Xu;
static inline int64_t S(uint32_t v) { return (int64_t)(int32_t)v; }
static inline uint32_t BF(f32 v) { uint32_t b; memcpy(&b, &v, 4); return b; }
static inline f32 FB(uint32_t b) { f32 v; memcpy(&v, &b, 4); return v; }
static inline uint64_t BD(f64 v) { uint64_t b; memcpy(&b, &v, 8); return b; }
static inline f64 DB(uint64_t b) { f64 v; memcpy(&v, &b, 8); return v; }
/* argument word n: $a0-$a3, then the caller's stack */
static inline uint32_t W(const uint64_t *r, int n) { return n < 4 ? (uint32_t)r[4 + n] : port_mips_lw((uint32_t)r[29] + 4u * (uint32_t)n); }
/* before the game's C runs: $a0-$a3 in its register words, for what it doesn't declare (adapt.py) */
static inline void A(const uint64_t *r) { for (int i = 0; i < 4; i++) port_mips_sw(port_mips_regs + 4u * (uint32_t)i, (uint32_t)r[4 + i]); }
"""


def _arg(where: tuple, t: str) -> str:
    """C reading an argument of type `t` from where o32 passed it (registers `r`, float registers `f`)."""
    kind, n = where
    if kind == "fpr":
        return f"FB(f[{n}])"
    if kind == "dfpr":
        return f"DB((uint64_t)f[{n + 1}] << 32 | f[{n}])"
    if kind == "gpr":
        return f"W(r, {n})"
    if kind == "gprf":
        return f"FB(W(r, {n}))"
    pair = f"((uint64_t)W(r, {n}) << 32 | W(r, {n + 1}))"
    return pair if kind == "gpr64" else f"DB({pair})"


def _put(where: tuple, value: str) -> str:
    """C putting `value` where o32 passes it, into `r` and `f` (the stack's words through the MIPS stack)."""
    kind, n = where
    word = (lambda s, v: f"r[{4 + s}] = S((uint32_t)({v}));" if s < 4 else f"port_mips_sw((uint32_t)r[29] + {4 * s}u, (uint32_t)({v}));")
    if kind == "fpr":
        return f"f[{n}] = BF({value});"
    if kind == "dfpr":
        return f"{{ uint64_t b_ = BD({value}); f[{n}] = (uint32_t)b_; f[{n + 1}] = (uint32_t)(b_ >> 32); }}"
    if kind == "gpr":
        return word(n, value)
    if kind == "gprf":
        return word(n, f"BF({value})")
    v = value if kind == "gpr64" else f"BD({value})"
    return word(n, f"(uint64_t)({v}) >> 32") + " " + word(n + 1, f"(uint64_t)({v})")


def _set_result(ret: str, value: str) -> str:
    """C leaving a C function's result where o32 returns it."""
    return {"void": f"{value}; r[2] = S(port_mips_lw(port_mips_regs + 16u));",
            "u32": f"r[2] = S((uint32_t)({value}));",
            "u64": f"{{ uint64_t v_ = {value}; r[2] = S((uint32_t)(v_ >> 32)); r[3] = S((uint32_t)v_); }}",
            "f32": f"f[0] = BF({value});",
            "f64": f"{{ uint64_t b_ = BD({value}); f[0] = (uint32_t)b_; f[1] = (uint32_t)(b_ >> 32); }}"}[ret]


def _returned(ret: str) -> str:
    return {"void": "", "u32": "return (u32)r[2];", "u64": "return (u64)(uint32_t)r[2] << 32 | (uint32_t)r[3];",
            "f32": "return FB(f[0]);", "f64": "return DB((uint64_t)f[1] << 32 | f[0]);"}[ret]


def _next_word(places: list[tuple]) -> int:
    """The argument word after the ones o32 gave these arguments: where a variadic function's extra ones start."""
    return max([0] + [n + (2 if k in ("gpr64", "gprd") else 1) for k, n in places if k.startswith("gpr")]
               + [2 * len([p for p in places if p[0] in ("fpr", "dfpr")])])


def variadic(lls: list[Path]) -> set[str]:
    """The variadic functions: in WebAssembly their extra arguments come as a pointer to a buffer of them, the last
    parameter, where o32 passes them as more argument words. A function's own definition says so; without one (a
    function with no C), a declaration with fixed parameters before its `...`. An unprototyped declaration
    (`s32 taskOpen();`) is `(...)` in the IR too, and isn't: taken for one, a racing game's taskOpen got its third
    argument as a buffer's address and returned no queue."""
    defined, declared = {}, {}
    for ll in lls:
        for m in re.finditer(r"^(define|declare) [^@\n]*@([\w.$]+)\(([^\n]*)\)", Path(ll).read_text(encoding="utf-8"), re.M):
            params = [p.strip() for p in split_top(m.group(3))]
            fixed_then_more = params[-1:] == ["..."] and len(params) > 1
            if m.group(1) == "define":
                defined[m.group(2)] = fixed_then_more
            else:
                declared[m.group(2)] = declared.get(m.group(2), False) or fixed_then_more
    return {n for n, v in defined.items() if v} | {n for n, v in declared.items() if v and n not in defined}


def _layout(text: str, types: dict) -> tuple[int, int]:
    """(size, alignment) in bytes of an LLVM type as wasm32 lays it out: integers, floats, pointers, arrays and
    structures (named ones from `types`, the module's `%name = type {...}`)."""
    text = text.strip()
    if text.startswith("<{"):  # packed
        return sum(_layout(t, types)[0] for t in split_top(text[2:-2])), 1
    if text.startswith("{"):
        size, align = 0, 1
        for t in split_top(text[1:-1]) if text[1:-1].strip() else []:
            s, a = _layout(t, types)
            size = (size + a - 1) // a * a + s
            align = max(align, a)
        return (size + align - 1) // align * align, align
    if text.startswith("["):
        m = re.fullmatch(r"\[\s*(\d+)\s*x\s*(.+)\]", text)
        s, a = _layout(m.group(2), types)
        return int(m.group(1)) * s, a
    if text.startswith("%"):
        return _layout(types[text], types) if text in types else (4, 4)
    if (m := re.fullmatch(r"i(\d+)", text)):
        n = max(1, int(m.group(1)) // 8)
        return n, min(n, 8)
    return {"float": (4, 4), "double": (8, 8), "ptr": (4, 4), "half": (2, 2)}.get(text, (4, 4))


def by_value(lls: list[Path], declared: bool = False) -> dict[str, dict[int, int]]:
    """{function: {parameter's position: its words}} for the structures it takes by value: in WebAssembly a pointer
    to a copy (`byval(%struct.X)`), where o32 passes the structure's words as argument words. Its size from the
    module's type definitions: the arguments after one take the words after all of it (a racing game's menu
    function takes a 4-word structure and then two words, its 5th and 6th). From the functions' definitions, or
    with `declared` from their callers' declarations (a function with no C, which the interpreter runs)."""
    out = {}
    for ll in lls:
        text = Path(ll).read_text(encoding="utf-8")
        types = dict(re.findall(r"^(%[\w.$\"-]+) = type (.+)$", text, re.M))
        for m in re.finditer(r"^" + ("declare" if declared else "define") + r" [^@\n]*@([\w.$]+)\(([^\n]*)\)", text, re.M):
            if "byval" not in m.group(2):
                continue
            params = {}
            for i, p in enumerate(split_top(m.group(2))):
                if (b := re.search(r"byval\((.+?)\) align", p)):
                    params[i] = max(1, (_layout(b.group(1), types)[0] + 3) // 4)
            out[m.group(1)] = params
    return out


def _places_by_value(types: list[str], structs: dict[int, int]) -> list[tuple]:
    """Where o32 passes the arguments of a function taking structures by value: each structure ("struct", its first
    word) in as many words as it has, the rest in the words after (no float registers: a structure comes first)."""
    out, slot = [], 0
    for i, t in enumerate(types):
        if i in structs:
            out.append(("struct", slot))
            slot += structs[i]
        elif t in ("u64", "f64"):
            slot += slot % 2
            out.append(("gpr64" if t == "u64" else "gprd", slot))
            slot += 2
        else:
            out.append(("gpr" if t == "u32" else "gprf", slot))
            slot += 1
    return out


POINTER_CALL = re.compile(r"CALL_INDIRECT\([^,]+, ((?:void|u32|u64|f32|f64) \(\*\)\(void\*(?:, (?:u32|u64|f32|f64))*\)), ")
CODES = {"u32": 0, "u64": 1, "f32": 2, "f64": 3, "void": 0}


def pointer_types(texts) -> list[str]:
    """The C types the game's C calls through pointers as (wasm2c's CALL_INDIRECT, which bemem.py makes pass them to
    port_func_as as text), from the build's C."""
    return sorted({m.group(1) for text in texts for m in POINTER_CALL.finditer(text)})


def _pointer_entries(types: list[str]) -> list[str]:
    """For the native build, an entry of each type the game calls through pointers as: its arguments handed to the
    interpreter with their types (mips.c's port_mips_typed_call), floats where o32 puts them, its result as its type
    returns it. The function it runs is the one port_func_as was just asked for (port_mips_target)."""
    lines = ["#ifndef PORT_WEB", "uint32_t port_mips_target(void);",
             "typedef struct { const char *type; void *entry; } PortMipsPointerType;"]
    table = []
    for k, t in enumerate(types):
        m = re.fullmatch(r"(\w+) \(\*\)\(void\*((?:, \w+)*)\)", t)
        if not m:
            continue
        ret, params = m.group(1), [p.strip() for p in m.group(2).split(",") if p.strip()]
        decl = "".join(f", {p} a{i}" for i, p in enumerate(params))
        bits = {"u32": "(uint64_t)a{i}", "u64": "a{i}", "f32": "BF(a{i})", "f64": "BD(a{i})"}
        vals = ", ".join(bits[p].format(i=i) for i, p in enumerate(params)) or "0"
        codes = ", ".join(str(CODES[p]) for p in params) or "0"
        back = {"void": "", "u32": "return (u32)v_;", "u64": "return v_;", "f32": "return FB((uint32_t)v_);",
                "f64": "return DB(v_);"}[ret]
        lines.append(f"static {ret} P_{k}(void *g{decl}) {{ (void)g; static const uint8_t t_[] = {{{codes}}}; "
                     f"const uint64_t a_[] = {{{vals}}}; uint64_t v_ = port_mips_typed_call(port_mips_target(), t_, a_, "
                     f"{len(params)}, {CODES[ret]}); (void)v_; {back} }}")
        table.append(f'    {{"{t}", (void *)P_{k}}},')
    lines.append("const PortMipsPointerType port_mips_pointer_types[] = {")
    lines += table or ["    {0, 0},"]
    lines += ["};", f"const unsigned port_mips_pointer_type_count = {len(table)};", "#endif"]
    return lines


def _types(params: str) -> list[str]:
    return [t for t in re.findall(r"\b(u32|u64|f32|f64)\b", params)]


def mips_signatures(lls: list[Path], fixed: list[str], hosts: list[Path], library_names=None, left_out=(),
                    replaced=lambda name: False, by_value_calls=()) -> list[str]:
    """The functions the game's C calls and has no C for, which the interpreter runs: each gets MIPS's own shape in
    the build's one signature per function (recomp.MIPS_SIGNATURE), as recompiled C's do (recomp.mips_signatures).
    Its callers may each declare it their own way (a function one file calls with no arguments and another with
    one, which wasm-ld refuses to link as one import), and MIPS passed whatever was in the registers: adapt.py's
    thunks fill what a call leaves out from the register words. Not those its callers pass a structure by value
    (`by_value_calls`): those keep their declared shape, whose pointer to the structure the bridge copies in from."""
    library_names = library_names or {}
    defined, declared = set(), set()
    for ll in lls:
        for m in re.finditer(r"^(define|declare) [^@\n]*@([\w.$]+)\(", Path(ll).read_text(encoding="utf-8"), re.M):
            (defined if m.group(1) == "define" else declared).add(m.group(2))
    hosted = {_demangle(m.group(2)) for path in hosts
              for m in HOST.finditer(Path(path).read_text(encoding="utf-8", errors="replace"))}
    where = _addresses(fixed)
    out = []
    for n in sorted(declared - defined):
        lib = library_names.get(n, n)
        if (n.startswith("llvm.") or _vram(n, where) is None or lib in hosted or n in left_out or lib in left_out
                or replaced(lib) or replaced(n)):
            continue
        if n in by_value_calls:
            continue
        out.append(n)
    return out


def generate(game_h: str, fixed: list[str], hosts: list[Path], library_names=None, defined=(), left_out=(),
             replaced=lambda name: False, varargs=(), byval=None, byval_calls=None, pointer_types=(),
             *, renames=None, patterns=()) -> tuple[str, dict]:
    """interp.c's text, and how many of each it has: {"game", "host", "imports"}. `fixed`: the build's rows of
    names and console addresses (`name address kind`); `hosts`: the host's C files (what it answers by name);
    `defined`: imports something else defines already (recompiled C's bridges). Not interpreted, as before them
    (stubs.py's, which skip them): `left_out`, functions the build leaves out on purpose (exclude.txt, the library
    code the host provides), and what `library` says is library code the host replaces (the port kit's
    sdk_group): libultra's own hardware code, run as it is, would drive hardware the host emulates a level above
    (the Controller Pak's serial transfers, interrupts). `varargs`: the variadic functions (variadic()); `byval`:
    their structures passed by value (by_value()): a pointer to its words where o32 put them (port_mips_slot), the
    arguments after it in the words after all of it; `byval_calls` the same for the functions with no C the game's C
    passes structures to (by_value(declared=True)): their words copied in. `pointer_types`: the C types the game's
    C calls through pointers as (pointer_types()), each given an entry for the interpreter in the native build."""
    byval = byval or {}
    byval_calls = byval_calls or {}
    library_names = library_names or {}
    where = _addresses(fixed)
    hosted = {}
    for path in hosts:
        for m in HOST.finditer(Path(path).read_text(encoding="utf-8", errors="replace")):
            ret, c, params = m.groups()
            hosted.setdefault(_demangle(c), (f"w2c_env_{c}", ret, _types(params)))
    lines = [HEADER % {"regs": REGS}]
    table = {}  # console address: the bridge's name
    counts = {"game": 0, "host": 0, "imports": 0}
    for m in EXPORT.finditer(game_h):
        name, ret, c, params = m.groups()
        vram = _vram(name, where)
        if vram is None or vram in table or ret not in ("void", "u32", "u64", "f32", "f64"):
            continue
        types = _types(params)
        if name in varargs and types:  # its extra arguments as a buffer of the words after its fixed ones
            fixed_types = types[:-1]
            places = o32(fixed_types)
            args = "".join(f", {_arg(w, t)}" for w, t in zip(places, fixed_types))
            args += f", port_mips_varargs(r, {_next_word(places)})"
        else:
            structs = byval.get(name) or {}
            places = _places_by_value(types, structs) if structs else o32(types)
            args = "".join(f", port_mips_slot(r, {w[1]})" if w[0] == "struct" else f", {_arg(w, t)}"
                           for w, t in zip(places, types))
        bridge = f"C_{vram:08X}"
        lines.append(f"static void {bridge}(uint64_t *r, uint32_t *f) {{ (void)f; A(r); "
                     f"{_set_result(ret, f'{c}(port_game(){args})')} }}")
        table[vram] = bridge
        counts["game"] += 1
    used = {}
    named = dict(where)  # every function by name: the split's names, and library detection's for automatic ones
    for name in library_names:
        if name not in named and (vram := _vram(name, where)) is not None:
            named[name] = vram
    for name, vram in sorted(named.items(), key=lambda x: x[1]):
        library = library_names.get(name, name)
        if vram in table or library not in hosted:
            continue
        c, ret, types = hosted[library]
        used[library] = hosted[library]
        args = "".join(f", {_arg(w, t)}" for w, t in zip(o32(types), types))
        bridge = f"H_{vram:08X}"
        lines.append(f"static void {bridge}(uint64_t *r, uint32_t *f) {{ (void)f; {_set_result(ret, f'{c}(NULL{args})')} }}")
        table[vram] = bridge
        counts["host"] += 1
    for name, _, _ in patterns:
        if name in hosted:
            used[name] = hosted[name]
    shapes = [n for n in SHAPE_NAMES if n in hosted and hosted[n][1] in ("void", "u32", "u64", "f32", "f64")]
    for name in shapes:
        used[name] = hosted[name]
    at = 1  # the host's functions the bridges call, declared before them
    lines[at:at] = [f"{ret} {c}(struct w2c_env *" + "".join(f", {t}" for t in types) + ");"
                    for c, ret, types in sorted(used.values())]
    imports = _import_addresses(where, renames or {})
    for m in IMPORT.finditer(game_h):
        name, ret, c, params = m.groups()
        vram = _vram(name, imports)
        lib = library_names.get(name, name)
        if (vram is None or vram in table or c in defined or _demangle(c[len("w2c_env_"):]) in hosted
                or lib in hosted or name in left_out or lib in left_out or replaced(lib) or replaced(name)):
            continue
        types = _types(params)
        decl = "".join(f", {t} a{i}" for i, t in enumerate(types))
        if byval_calls.get(name):  # a structure by value: its words copied in where o32 passes it
            places = _places_by_value(types, byval_calls[name])
            words = max([4] + [n + (byval_calls[name][i] if k == "struct" else 2 if k in ("gpr64", "gprd") else 1)
                               for i, (k, n) in enumerate(places)])
            puts = " ".join(f"port_mips_copy_in(r, {w[1]}, (uint32_t)a{i}, {byval_calls[name][i]});" if w[0] == "struct"
                            else _put(w, f"a{i}") for i, w in enumerate(places))
        elif name in varargs and types:  # the C's buffer of extra arguments, as the words after the fixed ones
            places = o32(types[:-1])
            first = _next_word(places)
            words = first + 16
            puts = " ".join(_put(w, f"a{i}") for i, w in enumerate(places))
            puts += f" port_mips_spread(r, {first}, (uint32_t)a{len(types) - 1});"
        else:
            places = o32(types)
            words = max([4, _next_word(places)])
            puts = " ".join(_put(w, f"a{i}") for i, w in enumerate(places))
        fail = "return;" if ret == "void" else "return 0;"
        lines.append(f"{ret} {c}(struct w2c_env *e{decl}) {{ (void)e; uint64_t r[32]; uint32_t f[32]; "
                     f"if (!port_mips_enter(r, f, {words})) {{ static int said; if (!said++) fprintf(stderr, "
                     f"\"{name}: no C for it (the interpreter is off): skipped\\n\"); {fail} }} "
                     f"{puts} port_mips_run(0x{vram:08X}u, r, f); port_mips_leave(r); {_returned(ret)} }}")
        counts["imports"] += 1
    pattern_rows, pattern_calls = [], {}
    for name, words, masks in patterns:
        if name not in hosted:
            continue
        c, ret, types = hosted[name]
        if ret not in ("void", "u32", "u64", "f32", "f64"):
            continue
        args = "".join(f", {_arg(w, t)}" for w, t in zip(o32(types), types))
        index = len(pattern_rows)
        if name not in pattern_calls:
            pattern_calls[name] = f"H_pattern_{index}"
            lines.append(f"static void {pattern_calls[name]}(uint64_t *r, uint32_t *f) {{ (void)f; "
                         f"{_set_result(ret, f'{c}(NULL{args})')} }}")
        lines.append(f"static const uint32_t pattern_words_{index}[] = {{" + ", ".join(f"0x{w:08X}u" for w in words) + "};")
        lines.append(f"static const uint32_t pattern_masks_{index}[] = {{" + ", ".join(f"0x{w:08X}u" for w in masks) + "};")
        pattern_rows.append(f"    {{pattern_words_{index}, pattern_masks_{index}, {len(words)}, {pattern_calls[name]}}},")
    lines.append("const PortMipsPattern port_mips_patterns[] = {")
    lines += pattern_rows or ["    {0, 0, 0, 0},"]
    lines.append("};")
    lines.append(f"const unsigned port_mips_pattern_count = {len(pattern_rows)};")
    # libultra routines told by structure at run time (mips.c's shape_identify): each the host defines, by name
    for name in shapes:
        c, ret, types = hosted[name]
        args = "".join(f", {_arg(w, t)}" for w, t in zip(o32(types), types))
        lines.append(f"static void H_shape_{name}(uint64_t *r, uint32_t *f) {{ (void)f; "
                     f"{_set_result(ret, f'{c}(NULL{args})')} }}")
    lines.append("const PortMipsShape port_mips_shapes[] = {")
    lines += [f'    {{"{name}", H_shape_{name}}},' for name in shapes] or ["    {0, 0},"]
    lines.append("};")
    lines.append(f"const unsigned port_mips_shape_count = {len(shapes)};")
    lines += _pointer_entries(pointer_types)
    lines.append("const PortMipsEntry port_mips_calls[] = {")
    lines += [f"    {{0x{v:08X}u, {b}}}," for v, b in sorted(table.items())] or ["    {0, 0},"]
    lines.append("};")
    lines.append(f"const unsigned port_mips_call_count = {len(table)};")
    return "\n".join(lines) + "\n", counts
